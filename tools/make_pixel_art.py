#!/usr/bin/env python3
"""Writes Shared/PixelArt.swift from art/pixels/<state>-{compact,wide}.txt and art/palette.json.

Usage:  python3 tools/make_pixel_art.py            (rewrites Shared/PixelArt.swift)

Grid rules: "." is transparent, any other character is looked up in the palette. All rows of one grid
must have the same width. Compact and wide grids of one state must share a height. The Swift side is
size-agnostic: whatever size you draw is what the island shows, one art pixel = `scale` points.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "art"
OUT = ROOT / "Shared" / "PixelArt.swift"

palette = json.loads((ART / "palette.json").read_text())
states = sorted({p.name.split("-")[0] for p in (ART / "pixels").glob("*-compact.txt")})
assert states, "no art/pixels/<state>-compact.txt found"


def grid(name):
    rows = [r for r in (ART / "pixels" / f"{name}.txt").read_text().split("\n") if r]
    widths = {len(r) for r in rows}
    assert len(widths) == 1, f"{name}: ragged rows {widths}"
    for r in rows:
        for ch in r:
            assert ch == "." or ch in palette, f"{name}: {ch!r} is not in palette.json"
    return rows


def swift_rows(rows):
    return "\n".join(f'        "{r}",' for r in rows)


def ident(state):
    head, *rest = state.split("_")
    return head + "".join(part.capitalize() for part in rest)


parts = []
for state in states:
    compact, wide = grid(f"{state}-compact"), grid(f"{state}-wide")
    assert len(compact) == len(wide), f"{state}: compact and wide heights differ"
    parts.append(f"    static let {ident(state)}Compact: [String] = [\n{swift_rows(compact)}\n    ]")
    parts.append(f"    static let {ident(state)}Wide: [String] = [\n{swift_rows(wide)}\n    ]")

enum_cases = "\n".join(f'    case {ident(s)} = "{s}"' for s in states)
switch_cases = "\n".join(
    f"        case .{ident(s)}: return wide ? PixelGrids.{ident(s)}Wide : PixelGrids.{ident(s)}Compact" for s in states)
pal = "\n".join(f'        "{k}": 0x{v.lstrip("#")},' for k, v in palette.items())
fallback = ident("calm") if "calm" in states else ident(states[0])

OUT.write_text(f'''// GENERATED by tools/make_pixel_art.py from art/pixels/*.txt and art/palette.json. Edit the art, not this.
//
// Pixel sprites for the Live Activity, shared by the App and the widget extension. Each grid cell
// becomes one pixel of a CGImage; SwiftUI scales it with interpolation off, so one art pixel is always
// a whole number of points (or a clean 2/3 on 3x screens) and is never smoothed.

import CoreGraphics
import Foundation
import SwiftUI

enum SpriteState: String, CaseIterable, Codable {{
{enum_cases}

    /// Unknown names from the server fall back to the default sprite rather than to nothing.
    init(name: String?) {{ self = SpriteState(rawValue: name ?? "") ?? .{fallback} }}

    func grid(wide: Bool) -> [String] {{
        switch self {{
{switch_cases}
        }}
    }}
}}

enum PixelGrids {{
    static let palette: [Character: UInt32] = [
{pal}
    ]

{chr(10).join(parts)}
}}

enum PixelArt {{
    private static let lock = NSLock()
    private static var cache: [String: CGImage] = [:]

    /// The grid as a CGImage, one pixel per cell. `gray` desaturates it (a stale island); `crop` cuts a
    /// window (x, y, w, h) out of the grid, which the minimal island uses.
    static func image(_ rows: [String], key: String, gray: Bool = false, crop: PixelCrop? = nil) -> CGImage? {{
        let cacheKey = "\\(key)|\\(gray)|\\(crop.map {{ "\\($0.x),\\($0.y),\\($0.w),\\($0.h)" }} ?? "-")"
        lock.lock(); defer {{ lock.unlock() }}
        if let hit = cache[cacheKey] {{ return hit }}
        let full = rows.map {{ $0.count }}.max() ?? 0
        let x0 = crop?.x ?? 0, y0 = crop?.y ?? 0
        let height = min(crop?.h ?? rows.count, rows.count - y0)
        let width = min(crop?.w ?? full, full - x0)
        guard width > 0, height > 0 else {{ return nil }}
        var bytes = [UInt8](repeating: 0, count: width * height * 4)
        for (y, row) in rows.dropFirst(y0).prefix(height).enumerated() {{
            for (x, cell) in row.dropFirst(x0).prefix(width).enumerated() {{
                guard let rgb = PixelGrids.palette[cell] else {{ continue }}
                var r = Double((rgb >> 16) & 0xFF), g = Double((rgb >> 8) & 0xFF), b = Double(rgb & 0xFF)
                var a = 255.0
                if gray {{
                    let l = 0.299 * r + 0.587 * g + 0.114 * b
                    r = 70 + l * 0.5; g = r; b = r; a = 200
                }}
                let i = (y * width + x) * 4
                // Premultiplied RGBA.
                bytes[i] = UInt8(r * a / 255); bytes[i + 1] = UInt8(g * a / 255)
                bytes[i + 2] = UInt8(b * a / 255); bytes[i + 3] = UInt8(a)
            }}
        }}
        guard let provider = CGDataProvider(data: Data(bytes) as CFData),
              let image = CGImage(width: width, height: height, bitsPerComponent: 8, bitsPerPixel: 32,
                                  bytesPerRow: width * 4, space: CGColorSpaceCreateDeviceRGB(),
                                  bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.premultipliedLast.rawValue),
                                  provider: provider, decode: nil, shouldInterpolate: false,
                                  intent: .defaultIntent) else {{ return nil }}
        cache[cacheKey] = image
        return image
    }}
}}

struct PixelCrop: Hashable {{
    var x: Int, y: Int, w: Int, h: Int
}}

/// One art pixel = `scale` points, never interpolated.
struct PixelImage: View {{
    let rows: [String]
    let key: String
    var scale: CGFloat = 1
    var gray: Bool = false
    var crop: PixelCrop? = nil

    var body: some View {{
        let full = rows.first?.count ?? 0
        let width = min(crop?.w ?? full, full - (crop?.x ?? 0))
        let height = min(crop?.h ?? rows.count, rows.count - (crop?.y ?? 0))
        if let image = PixelArt.image(rows, key: key, gray: gray, crop: crop) {{
            Image(decorative: image, scale: 1)
                .resizable()
                .interpolation(.none)
                .antialiased(false)
                .frame(width: CGFloat(width) * scale, height: CGFloat(height) * scale)
        }} else {{
            Color.clear.frame(width: CGFloat(width) * scale, height: CGFloat(height) * scale)
        }}
    }}
}}

struct SpriteView: View {{
    let state: SpriteState
    var wide = false
    var scale: CGFloat = 1
    var gray = false
    var crop: PixelCrop? = nil

    var body: some View {{
        PixelImage(rows: state.grid(wide: wide), key: state.rawValue + (wide ? "-wide" : "-compact"),
                   scale: scale, gray: gray, crop: crop)
    }}
}}

extension SpriteState {{
    /// The small "online" dot's colour in the compact island.
    static let onlineGreen = Color(red: 0x6F / 255.0, green: 0xB3 / 255.0, blue: 0x6B / 255.0)
}}
''')
print("wrote", OUT.relative_to(ROOT), "states:", ", ".join(states))
